#!/usr/bin/env python3
"""
FORGEFALL ambient / movement / UI / enemy sound synthesizer — Worker B, Goal 2 (SOUND).

Synthesizes ONLY Worker B's owned WAVs (movement, UI-adjacent, enemy cues)
with Python stdlib ONLY (wave, struct, math, random). Does NOT touch
tools/gen_audio.py (Worker A) or scripts/audio/audio_manager.gd (Worker A).

Output: 16-bit mono WAV @ 44100 Hz into ../assets/audio/

DESIGN RULES (Goal 2, binding):
- Volumes sane: every WAV is peak-normalized to <= 0.85, and call sites
  pass negative caller vol_db on top, so nothing ever reaches the 0 dB
  gunshot reference.
- NO stacking / NO forever loops: every new sound is a ONE-SHOT. The only
  loop this file writes is grapple_zip (regenerated, seamless crossfade),
  whose start/stop is already a single guarded pair in grapple_hook.gd
  (start_loop_2d on fire, stop_loop_2d on release — idempotent).
- Wall-run scrape and slide whoosh are LONG ONE-SHOTS fired once on state
  entry (wall-run <= 3.0 s, so a 2.8 s scrape covers the whole run) —
  deliberately NOT loops, so there is no stop path to leak.
- No second hit sound: the HUD solely owns the hit tick (Goal 1 dedupe) —
  an enemy_hit.wav was generated by an earlier draft and deleted during
  integration; do not re-add a hit sound to take_damage.

Run:  python3 tools/gen_audio_ambient.py   (from the forgefall project root)
"""

import math
import os
import random
import struct
import wave

# ----------------------------------------------------------------------------
# Config
# ----------------------------------------------------------------------------

SR = 44100  # sample rate, Hz

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.normpath(os.path.join(SCRIPT_DIR, "..", "assets", "audio"))

# ----------------------------------------------------------------------------
# Synthesis helpers (self-contained copies of the standard recipes)
# ----------------------------------------------------------------------------


def _n(dur_s):
    """Sample count for a duration in seconds."""
    return max(1, int(dur_s * SR))


def white(dur_s, seed=1):
    """White noise buffer, -1..1."""
    rng = random.Random(seed)
    n = _n(dur_s)
    return [rng.uniform(-1.0, 1.0) for _ in range(n)]


def tone(f0, f1, dur_s, wave="sine", phase=0.0):
    """Oscillator with linear freq sweep. wave: sine | square | saw."""
    n = _n(dur_s)
    out = [0.0] * n
    ph = phase
    for i in range(n):
        k = i / (n - 1) if n > 1 else 0.0
        f = f0 + (f1 - f0) * k
        ph += 2.0 * math.pi * f / SR
        s = math.sin(ph)
        if wave == "sine":
            out[i] = s
        elif wave == "square":
            out[i] = 1.0 if s >= 0.0 else -1.0
        else:  # saw
            out[i] = 2.0 * ((ph / (2.0 * math.pi)) % 1.0) - 1.0
    return out


def exp_decay(n, tau_s, delay_s=0.0):
    """Exponential decay envelope, tau in seconds, optional delay."""
    d = int(delay_s * SR)
    inv = 1.0 / (tau_s * SR)
    return [math.exp(-max(0.0, i - d) * inv) if i >= d else 0.0 for i in range(n)]


def attack(n, attack_s):
    """Linear attack ramp envelope 0..1."""
    a = max(1, int(attack_s * SR))
    env = [1.0] * n
    for i in range(min(a, n)):
        env[i] = i / a
    return env


def amod(x, env):
    """Amplitude-modulate signal by envelope."""
    return [v * e for v, e in zip(x, env)]


def lowpass(x, cutoff_hz):
    """One-pole lowpass."""
    a = 1.0 - math.exp(-2.0 * math.pi * cutoff_hz / SR)
    y = 0.0
    out = [0.0] * len(x)
    for i, v in enumerate(x):
        y += a * (v - y)
        out[i] = y
    return out


def highpass(x, cutoff_hz):
    """One-pole highpass (via lowpass subtraction)."""
    lp = lowpass(x, cutoff_hz)
    return [v - l for v, l in zip(x, lp)]


def bandpass(x, lo_hz, hi_hz):
    """Crude bandpass: highpass then lowpass."""
    return lowpass(highpass(x, lo_hz), hi_hz)


def place(dst, src, at_s, gain=1.0):
    """Mix src into dst at time offset (seconds)."""
    o = int(at_s * SR)
    for i, v in enumerate(src):
        j = o + i
        if 0 <= j < len(dst):
            dst[j] += v * gain
    return dst


def add(a, b):
    """Sum two equal-length buffers."""
    return [x + y for x, y in zip(a, b)]


def normalize(x, peak=0.9):
    """Peak-normalize to target peak amplitude."""
    m = max(max(x), -min(x), 1e-9)
    s = peak / m
    return [v * s for v in x]


def fade_edges(x, in_s=0.005, out_s=0.01):
    """Short fades to kill clicks at file boundaries."""
    n = len(x)
    fi = max(1, int(in_s * SR))
    fo = max(1, int(out_s * SR))
    out = list(x)
    for i in range(min(fi, n)):
        out[i] *= i / fi
    for i in range(min(fo, n)):
        out[n - 1 - i] *= i / fo
    return out


def make_loop(x, fade_s=0.25):
    """Crossfade tail into head so the buffer loops seamlessly."""
    f = max(2, int(fade_s * SR))
    n = len(x)
    out = x[: n - f]
    for i in range(f):
        k = i / f
        out[i] = x[i] * k + x[n - f + i] * (1.0 - k)
    return out


def write_wav(name, x):
    """Clamp, convert to 16-bit mono, write WAV, print result."""
    x = [max(-1.0, min(1.0, v)) for v in x]
    data = struct.pack("<%dh" % len(x), *[int(v * 32767) for v in x])
    os.makedirs(OUT_DIR, exist_ok=True)
    path = os.path.join(OUT_DIR, name + ".wav")
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(data)
    print("wrote %-22s %7d samples  %7.1f KB" % (name + ".wav", len(x), len(data) / 1024.0))


# ----------------------------------------------------------------------------
# Sound definitions
# ----------------------------------------------------------------------------


def build_all():
    sounds = {}

    # --- Footsteps (regenerated) -------------------------------------------
    # Goal 1 made the player faster (sprint 11 m/s -> ~5 steps/s). The old
    # samples were fine at walk cadence but smeared at sprint cadence, so
    # these have SHORTER decays + sharper transient attacks. Speed weighting
    # (pitch/volume by horizontal speed) lives in player.gd, not here.
    fc = white(0.13, 100)
    fc = highpass(fc, 900.0)
    fc = lowpass(fc, 5200.0)
    fc = amod(fc, exp_decay(len(fc), 0.022))  # was 0.028: tighter at sprint
    knock = tone(210, 150, 0.08, "sine")
    knock = amod(knock, exp_decay(len(knock), 0.024))
    sounds["footstep_concrete"] = fade_edges(
        normalize(add(fc, amod(knock, [0.5] * len(knock))), 0.8))

    fd = white(0.15, 101)
    fd = lowpass(fd, 700.0)
    fd = amod(fd, exp_decay(len(fd), 0.04))  # was 0.05: softer tail
    sounds["footstep_dirt"] = fade_edges(normalize(fd, 0.75))

    fm = white(0.22, 102)
    fm = highpass(fm, 1500.0)
    fm = amod(fm, exp_decay(len(fm), 0.04))
    for f, g in [(420.0, 0.5), (630.0, 0.3)]:
        p = tone(f, f * 0.99, 0.22, "sine")
        p = amod(p, exp_decay(len(p), 0.10))  # was 0.12: shorter ring
        place(fm, p, 0.0, g)
    sounds["footstep_metal"] = fade_edges(normalize(fm, 0.8))

    # --- Grapple zip (regenerated loop) -------------------------------------
    # Same 0.9 s seamless loop the grapple code already starts/stops, but
    # re-voiced: less raw white-noise hiss (fatiguing over a long zip),
    # more airy band-swept rush. Loop crossfade keeps it click-free.
    gz = white(0.9, 81)
    gz = bandpass(gz, 300.0, 3500.0)
    n = len(gz)
    sweep = [0.3 + 0.7 * math.sin(math.pi * i / n) for i in range(n)]
    gz = amod(gz, sweep)
    sounds["grapple_zip"] = normalize(make_loop(gz, 0.20), 0.75)  # was 0.85

    # --- Slide whoosh (NEW, one-shot) ---------------------------------------
    # Fired ONCE on slide entry. 0.7 s band-swept noise: fast attack,
    # rising then falling band — a body sliding over dustline grit.
    sw = white(0.7, 300)
    n = len(sw)
    out = [0.0] * n
    # Time-varying bandpass: sweep 400->2400 Hz in the first 0.25 s, back down.
    # Implemented as a slow crossfade between two fixed filtered copies.
    lo = bandpass(sw, 300.0, 900.0)
    hi = bandpass(sw, 1200.0, 3200.0)
    for i in range(n):
        k = i / n
        w = math.sin(math.pi * min(1.0, k * 1.6))  # rise then fall
        out[i] = lo[i] * (1.0 - w) + hi[i] * w
    out = amod(out, amod(attack(n, 0.03), exp_decay(n, 0.28)))
    sounds["slide_whoosh"] = fade_edges(normalize(out, 0.8))

    # --- Wall-run scrape (NEW, one-shot, NOT a loop) -------------------------
    # Fired ONCE on wall-run entry. 2.8 s long so it covers the whole run
    # (WALLRUN_MAX_TIME = 3.0 s) with no loop machinery and no stop path
    # to leak. Gritty bandpassed scrape + sparse metallic ticks, decaying
    # naturally to silence before the run can end.
    wr = white(2.8, 301)
    wr = bandpass(wr, 800.0, 4500.0)
    n = len(wr)
    # Irregular scrape texture: slow random-ish amplitude wander.
    rng = random.Random(302)
    wander = []
    v = 0.7
    for i in range(n):
        if i % 4410 == 0:  # retarget every 0.1 s
            v = rng.uniform(0.45, 1.0)
        wander.append(v)
    wr = amod(wr, wander)
    wr = amod(wr, amod(attack(n, 0.05), exp_decay(n, 1.4, delay_s=0.4)))
    # Sparse metallic ticks: mag-boots catching the wall.
    for i, at in enumerate([0.15, 0.55, 1.05, 1.6, 2.2]):
        tick = tone(1900.0 + i * 130.0, 1200.0, 0.06, "sine")
        tick = amod(tick, exp_decay(len(tick), 0.02))
        place(wr, tick, at, 0.25)
    sounds["wallrun_scrape"] = fade_edges(normalize(wr, 0.75), out_s=0.15)

    # --- Enemy death (NEW, one-shot) ----------------------------------------
    # Wired ONCE per enemy in die() (guarded by the dead flag). A voxel
    # crumble: short noise crunch + descending low thump. Distinct from
    # the hit tick (different event, different moment) — not a dupe.
    ed = [0.0] * _n(0.5)
    crunch = white(0.22, 311)
    crunch = bandpass(crunch, 500.0, 3000.0)
    crunch = amod(crunch, exp_decay(len(crunch), 0.06))
    place(ed, crunch, 0.0, 0.7)
    thump = tone(120, 38, 0.5, "sine")
    thump = amod(thump, exp_decay(len(thump), 0.16))
    place(ed, thump, 0.02, 0.9)
    sounds["enemy_death"] = fade_edges(normalize(ed, 0.8))

    # --- Brute footstep (NEW, one-shot) -------------------------------------
    # Heavy low thud + dirt crunch, fired sparsely (every ~3 m of brute
    # travel, ~1.25 s at brute speed) — never a loop, never stacked.
    bf = [0.0] * _n(0.35)
    low = tone(65, 32, 0.35, "sine")
    low = amod(low, exp_decay(len(low), 0.10))
    place(bf, low, 0.0, 1.0)
    dirt = white(0.30, 312)
    dirt = lowpass(dirt, 500.0)
    dirt = amod(dirt, exp_decay(len(dirt), 0.09))
    place(bf, dirt, 0.0, 0.6)
    sounds["footstep_brute"] = fade_edges(normalize(bf, 0.85))

    # --- Spawn telegraph (NEW, one-shot) ------------------------------------
    # Replaces portal_open for non-brute spawns: a distinct rising chirp
    # (660 -> 990 Hz, tremolo) that says "enemy incoming" without
    # borrowing the portal sound. Brutes keep the juggernaut horn.
    st = tone(660.0, 990.0, 0.45, "sine")
    trem = [0.6 + 0.4 * math.sin(2 * math.pi * 9.0 * i / SR) for i in range(len(st))]
    st = amod(st, trem)
    st = amod(st, amod(attack(len(st), 0.04), exp_decay(len(st), 0.3, delay_s=0.05)))
    spark = white(0.05, 313)
    spark = highpass(spark, 3500.0)
    place(st, spark, 0.0, 0.3)
    sounds["spawn_telegraph"] = fade_edges(normalize(st, 0.75))

    return sounds


def main():
    sounds = build_all()
    for name, data in sounds.items():
        write_wav(name, data)
    print("\nDone: %d files -> %s" % (len(sounds), OUT_DIR))


if __name__ == "__main__":
    main()
